use super::*;

#[test]
fn top_level_without_project_injects_project_and_warns() -> TestResult {
    let host = new_host();
    seed_modules(&host, &["C", "CXX"])?;
    let mut interp = interp(&host, Vec::new());
    interp.set_project_injection(true);
    configure(
        &host,
        &mut interp,
        "cmake_minimum_required(VERSION 3.10)\nset(X 1)\n",
        0,
    )?;
    let text = stderr(&host);
    assert!(
        text.contains("CMake Warning (author) in CMakeLists.txt:"),
        "{text}"
    );
    assert!(text.contains("No project() command is present."), "{text}");
    assert_eq!(var(&mut interp, "PROJECT_NAME"), Some("Project".into()));
    assert_eq!(
        global(&mut interp, "ENABLED_LANGUAGES"),
        Some("C;CXX".into())
    );
    Ok(())
}

#[test]
fn project_injection_is_off_by_default_and_skips_files_with_project() -> TestResult {
    let host = new_host();
    seed_modules(&host, &[])?;
    let mut interp = interp(&host, Vec::new());
    configure(&host, &mut interp, "set(X 1)\n", 0)?;
    assert!(!stderr(&host).contains("No project() command"));
    let mut injected = interp_with_injection(&host);
    configure(
        &host,
        &mut injected,
        "if(FALSE)\n  project(Other NONE)\nendif()\n",
        0,
    )?;
    assert!(!stderr(&host).contains("No project() command"));
    Ok(())
}

fn interp_with_injection(host: &Arc<PureHost>) -> Interp {
    let mut interp = interp(host, Vec::new());
    interp.set_project_injection(true);
    interp
}

#[test]
fn configure_depends_property_adds_listfiles() -> TestResult {
    let host = new_host();
    seed_modules(&host, &[])?;
    let mut interp = interp(&host, Vec::new());
    configure(
        &host,
        &mut interp,
        "project(P NONE)\nset_property(DIRECTORY APPEND PROPERTY CMAKE_CONFIGURE_DEPENDS dep.txt /work/abs.txt)\n",
        0,
    )?;
    let files = interp
        .cx()
        .project()
        .dir(rcmake_model::DirId::ROOT)
        .listfiles
        .clone();
    assert!(
        files.iter().any(|file| file == "/work/src/dep.txt"),
        "{files:?}"
    );
    assert!(
        files.iter().any(|file| file == "/work/abs.txt"),
        "{files:?}"
    );
    Ok(())
}

#[test]
