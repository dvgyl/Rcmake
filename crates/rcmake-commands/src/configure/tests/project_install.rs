    let host = new_host();
    seed_modules(&host, &[])?;
    host.seed_file(
        Path::new("/work/src/inc.cmake"),
        b"function(f)\n  cmake_language(EVAL CODE [[message(WARNING w)]])\nendfunction()\n",
    )?;
    let mut interp = interp(&host, Vec::new());
