pub(super) fn contains(name: &[u8]) -> bool {
    if name.iter().any(|byte| matches!(byte, b'<' | b'>')) {
        let key: Vec<_> = name
            .iter()
            .copied()
            .filter(|byte| !matches!(byte, b'<' | b'>'))
            .collect();
        NAMES.binary_search(&key.as_slice()).is_ok()
    } else {
        NAMES.binary_search(&name).is_ok()
    }
}

