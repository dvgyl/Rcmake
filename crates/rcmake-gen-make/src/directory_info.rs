//! `CMakeFiles/CMakeDirectoryInformation.cmake` for each directory.

use rcmake_base::BString;
use rcmake_gen_common::GenError;
use rcmake_host::{Host, path};
use rcmake_model::{DirId, ProjectModel};

use crate::MakeDialect;
use crate::fortran::cmake_argument;

/// Write the dependency scanning settings of each directory, as CMake does.
///
/// The file gives the top directories and the include regular expressions of
/// `include_regular_expression()`.
pub(crate) fn write(
    host: &dyn Host,
    model: &ProjectModel,
    dialect: MakeDialect,
) -> Result<(), GenError> {
    let root = model.dir(DirId::ROOT);
    let header = format!(
        "# CMAKE generated file: DO NOT EDIT!\n# Generated by \"{}\" Generator, CMake Version 4.5\n\n# Relative path conversion top directories.\nset(CMAKE_RELATIVE_PATH_TOP_SOURCE ",
        dialect.generator_name()
    );
    for (_, directory) in model.dirs() {
        let mut out = Vec::new();
        out.extend_from_slice(header.as_bytes());
        cmake_argument(&mut out, &root.source_dir, false);
        out.extend_from_slice(b")\nset(CMAKE_RELATIVE_PATH_TOP_BINARY ");
        cmake_argument(&mut out, &root.binary_dir, false);
        out.extend_from_slice(b")\n\n");
        if !dialect.is_nmake() {
            out.extend_from_slice(
                b"# Force unix paths in dependencies.\nset(CMAKE_FORCE_UNIX_PATHS 1)\n\n\n",
            );
        }
        out.extend_from_slice(
            b"# The C and CXX include file regular expressions for this directory.\nset(CMAKE_C_INCLUDE_REGEX_SCAN ",
        );
        let scan = directory
            .props
            .get(b"INCLUDE_REGULAR_EXPRESSION")
            .map_or(b"^.*$".as_slice(), |value| value.as_slice());
        let complain = directory
            .props
            .get(b"_RCMAKE_INCLUDE_REGEX_COMPLAIN")
            .map_or(b"^$".as_slice(), |value| value.as_slice());
        cmake_argument(&mut out, scan, false);
        out.extend_from_slice(b")\nset(CMAKE_C_INCLUDE_REGEX_COMPLAIN ");
        cmake_argument(&mut out, complain, false);
        out.extend_from_slice(
            b")\nset(CMAKE_CXX_INCLUDE_REGEX_SCAN ${CMAKE_C_INCLUDE_REGEX_SCAN})\nset(CMAKE_CXX_INCLUDE_REGEX_COMPLAIN ${CMAKE_C_INCLUDE_REGEX_COMPLAIN})\n",
        );
        let file: BString = [directory.binary_dir.as_slice(), b"/CMakeFiles"]
            .concat()
            .into();
        crate::write_makefile(
            host,
            &path::to_native(&file),
            b"CMakeDirectoryInformation.cmake",
            &out,
        )?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use rcmake_host::{Host, PureHost, ReadRange};
    use rcmake_model::{DirId, ProjectModel};

    #[test]
    fn writes_the_include_regular_expressions_of_each_directory()
    -> Result<(), Box<dyn std::error::Error>> {
        let root = if cfg!(windows) { "C:/work" } else { "/work" };
        let host = PureHost::new(root.into(), format!("{root}/cmake").into());
        let mut model = ProjectModel::default();
        model.set_root_dirs(format!("{root}/src").into(), format!("{root}/build").into());
        model
            .dir_mut(DirId::ROOT)
            .props
            .set("INCLUDE_REGULAR_EXPRESSION".into(), "^custom$".into());
        super::write(&host, &model, crate::MakeDialect::Unix)?;
        let path = std::path::PathBuf::from(format!(
            "{root}/build/CMakeFiles/CMakeDirectoryInformation.cmake"
        ));
        let text = String::from_utf8(host.read(&path, ReadRange::All { limit: 4096 })?)?;
        assert!(text.contains("set(CMAKE_FORCE_UNIX_PATHS 1)"), "{text}");
        assert!(
            text.contains("set(CMAKE_C_INCLUDE_REGEX_SCAN \"^custom\\$\")"),
            "{text}"
        );
        assert!(
            text.contains("set(CMAKE_C_INCLUDE_REGEX_COMPLAIN \"^\\$\")"),
            "{text}"
        );

        super::write(&host, &model, crate::MakeDialect::NMake)?;
        let nmake = String::from_utf8(host.read(&path, ReadRange::All { limit: 4096 })?)?;
        assert!(nmake.contains("\"NMake Makefiles\""), "{nmake}");
        assert!(!nmake.contains("CMAKE_FORCE_UNIX_PATHS"), "{nmake}");
        assert!(
            nmake.contains("set(CMAKE_C_INCLUDE_REGEX_SCAN \"^custom\\$\")"),
            "{nmake}"
        );
        Ok(())
    }
}
