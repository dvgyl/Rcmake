//! Scan C-family includes and Fortran dependencies for `cmake -E cmake_depends`.

mod fortran;

pub use fortran::{FortranSource, FortranTarget};

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use rcmake_base::{BString, Limits};
use rcmake_host::{FileKind, Follow, Host, HostError, HostResult, ReadRange, WriteMode, path};

/// One source file and its Makefiles object output.
pub struct Source {
    /// Path to scan.
    pub input: PathBuf,
    /// Object path in the make rule.
    pub object: PathBuf,
    /// Directories searched for include files, in order.
    pub include_dirs: Vec<PathBuf>,
}

/// Write the make and internal dependency files for a target.
///
/// # Errors
///
/// Returns a host error if the scan exceeds its limits or a file cannot be written.
pub fn write(
    host: &dyn Host,
    generator: &BString,
    build_root: &Path,
    output_dir: &Path,
    sources: &[Source],
) -> HostResult<()> {
    write_files(host, generator, build_root, output_dir, sources, None)
}

/// Write include dependencies, Fortran module dependencies, and module stamp rules.
///
/// # Errors
///
/// Returns an error if a scan exceeds its limits, a module provider conflicts,
/// or a dependency file cannot be read or written.
pub fn write_with_fortran(
    host: &dyn Host,
    generator: &BString,
    build_root: &Path,
    output_dir: &Path,
    sources: &[Source],
    target: &FortranTarget,
) -> HostResult<()> {
    write_files(
        host,
        generator,
        build_root,
        output_dir,
        sources,
        Some(target),
    )
}

fn write_files(
    host: &dyn Host,
    generator: &BString,
    build_root: &Path,
    output_dir: &Path,
    sources: &[Source],
    fortran_target: Option<&FortranTarget>,
) -> HostResult<()> {
    let header = format!(
        "# CMAKE generated file: DO NOT EDIT!\n# Generated by \"{generator}\" Generator, CMake Version 4.5\n\n"
    );
    let mut rules = header.as_bytes().to_vec();
    let mut internal = rules.clone();
    let limit = Limits::default().max_file_read;
    let mut bytes_left = limit;
    for source in sources {
        let mut files = collect(host, source, &mut bytes_left)?;
        files.remove(&source.input);
        let object = relative(&source.object, build_root);
        super::depfile::escape(&object, &mut rules);
        rules.push(b':');
        internal.extend_from_slice(&object);
        for file in std::iter::once(&source.input).chain(files.iter()) {
            let file = relative(file, build_root);
            rules.extend_from_slice(b" \\\n ");
            super::depfile::escape(&file, &mut rules);
            internal.extend_from_slice(b"\n ");
            internal.extend_from_slice(&file);
            if rules.len() as u64 + internal.len() as u64 > limit {
                return Err(HostError::unsupported(
                    "Make dependency files exceed the size limit",
                ));
            }
        }
        rules.push(b'\n');
        internal.push(b'\n');
    }
    let fortran = fortran_target
        .map(|target| fortran::collect(host, build_root, output_dir, target, &mut bytes_left))
        .transpose()?;
    if let Some(output) = &fortran {
        rules.extend_from_slice(&output.rules);
        internal.extend_from_slice(&output.internal);
        if rules.len() as u64 + internal.len() as u64 > limit {
            return Err(HostError::unsupported(
                "Make dependency files exceed the size limit",
            ));
        }
    }
    host.write(&output_dir.join("depend.make"), &rules, WriteMode::Truncate)?;
    host.write(
        &output_dir.join("depend.internal"),
        &internal,
        WriteMode::Truncate,
    )?;
    if let Some(output) = fortran {
        output.write(host, output_dir)?;
    }
    Ok(())
}

fn relative(file: &Path, build_root: &Path) -> BString {
    path::from_native(file.strip_prefix(build_root).unwrap_or(file))
}

fn collect(
    host: &dyn Host,
    source: &Source,
    bytes_left: &mut u64,
) -> HostResult<BTreeSet<PathBuf>> {
    let mut files = BTreeSet::new();
    let mut visited = BTreeSet::new();
    let mut pending = vec![source.input.clone()];
    while let Some(file) = pending.pop() {
        let Ok(identity) = host.canonicalize(&file) else {
            continue;
        };
        if !visited.insert(identity) {
            continue;
        }
        if visited.len() > 100_000 {
            return Err(HostError::unsupported(
                "Make dependency scan exceeds the file limit",
            ));
        }
        let meta = host.metadata(&file, Follow::Yes)?;
        if meta.kind != FileKind::File {
            continue;
        }
        *bytes_left = bytes_left
            .checked_sub(meta.len)
            .ok_or_else(|| HostError::unsupported("Make dependency scan exceeds the size limit"))?;
        let content = host.read(&file, ReadRange::All { limit: meta.len })?;
        if content.starts_with(b"\xff\xfe")
            || content.starts_with(b"\xfe\xff")
            || content.contains(&0)
        {
            continue;
        }
        files.insert(file.clone());
        let content = content.strip_prefix(b"\xef\xbb\xbf").unwrap_or(&content);
        for (name, quoted) in content.split(|&byte| byte == b'\n').filter_map(include) {
            let name = path::to_native(name);
            let current = quoted.then(|| file.parent()).flatten();
            let dirs = current
                .into_iter()
                .chain(source.include_dirs.iter().map(PathBuf::as_path));
            if let Some(header) = dirs.map(|dir| dir.join(&name)).find(|header| {
                host.metadata(header, Follow::Yes)
                    .is_ok_and(|meta| meta.kind == FileKind::File)
            }) {
                pending.push(header);
            }
        }
    }
    Ok(files)
}

fn include(line: &[u8]) -> Option<(&[u8], bool)> {
    let directive = line
        .trim_ascii_start()
        .strip_prefix(b"#")?
        .trim_ascii_start();
    let argument = directive.strip_prefix(b"include")?.trim_ascii_start();
    let (&open, value) = argument.split_first()?;
    let close = match open {
        b'"' => b'"',
        b'<' => b'>',
        _ => return None,
    };
    let name = value.split(|&byte| byte == close).next()?;
    (name.len() < value.len() && !name.is_empty()).then_some((name, open == b'"'))
}
