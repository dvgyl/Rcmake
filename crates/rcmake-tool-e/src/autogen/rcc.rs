use std::path::{Path, PathBuf};

use rcmake_base::{
    BString,
    qt_resource::{MAX_RESOURCE_FILE_BYTES, parse},
};
use rcmake_host::path::from_native_cmake as from_native;

use super::{
    ITEM_LIMIT, Result, TOOL_TIMEOUT, ToolCtx, cache, ensure_parent, info::Rcc, output_path, read,
    remove, required_time, resolve, run_generator, run_tool, timestamp, touch, write_changed,
};

pub(super) fn run(cx: &ToolCtx<'_>, info: Rcc) -> Result<()> {
    ensure_parent(cx, &info.lock)?;
    let _lock = cx
        .host
        .lock_file(&info.lock, Some(TOOL_TIMEOUT))
        .map_err(|error| format!("Cannot lock \"{}\": {error}", info.lock.display()))?;
    let source_time = required_time(cx, &info.source)?;
    let tool_time = required_time(cx, &info.executable)?;
    let generated_include = info.common.multi.then(|| {
        let name = with_payload_suffix(&info.name);
        [info.checksum.as_slice(), b"/", name.as_slice()].concat()
    });
    let output = if let Some(include) = &generated_include {
        output_path(&info.common.include, include)?
    } else {
        info.public.clone()
    };
    let hash = settings_digest(&info);
    let settings = cache::settings(cx, &info.common.settings);
    let changed = settings.get(b"rcc".as_slice()) != Some(&hash);
    if changed {
        remove(cx, &info.common.settings)?;
    }
    let output_time = timestamp(cx, &output);
    let generate = match output_time {
        Some(time) if !changed && time >= source_time.max(tool_time) => {
            resources_changed(cx, &info, time)?
        }
        _ => true,
    };
    let mut output_updated = generate;
    if generate {
        let mut args = info.options.clone();
        args.extend(["-o".into(), from_native(&output), from_native(&info.source)]);
        run_generator(
            cx,
            &info.common,
            &info.executable,
            args,
            &info.source,
            &output,
            None,
        )?;
    } else if output_time
        .is_some_and(|time| timestamp(cx, &info.info).is_some_and(|info| time < info))
    {
        touch(cx, &output)?;
        output_updated = true;
    }
    if let Some(include) = generated_include {
        let content = [
            b"// This is an autogenerated configuration wrapper file.\n// Changes will be overwritten.\n#include <".as_slice(),
            &include,
            b">\n",
        ].concat();
        if !write_changed(cx, &info.public, &content)? && output_updated {
            touch(cx, &info.public)?;
        }
    }
    cache::write_settings(cx, &info.common.settings, [("rcc", Some(hash))])
}

fn resources_changed(
    cx: &ToolCtx<'_>,
    info: &Rcc,
    output_time: rcmake_host::FileTime,
) -> Result<bool> {
    let listed;
    let inputs = if info.inputs.is_empty() {
        listed = list_inputs(cx, info)?;
        &listed
    } else {
        &info.inputs
    };
    let mut changed = false;
    for input in inputs {
        let time = timestamp(cx, input).ok_or_else(|| {
            format!(
                "The resource file \"{}\" listed in \"{}\" does not exist.",
                input.display(),
                info.source.display()
            )
        })?;
        changed |= time > output_time;
    }
    Ok(changed)
}

fn settings_digest(info: &Rcc) -> String {
    let executable = from_native(&info.executable);
    let source = from_native(&info.source);
    let inputs = info
        .inputs
        .iter()
        .map(|path| from_native(path))
        .collect::<Vec<_>>();
    cache::settings_hash(
        std::iter::once(&executable)
            .chain(&info.list_options)
            .chain([&source, &info.checksum, &info.name])
            .chain(&info.options)
            .chain(&inputs)
            .map(|value| value.as_slice()),
    )
}

fn with_payload_suffix(name: &[u8]) -> BString {
    let index = name
        .iter()
        .rposition(|&byte| byte == b'.')
        .unwrap_or(name.len());
    let (stem, extension) = name.split_at(index);
    [stem, b"_CMAKE_", extension].concat().into()
}

fn list_inputs(cx: &ToolCtx<'_>, info: &Rcc) -> Result<Vec<PathBuf>> {
    let dir = info
        .source
        .parent()
        .ok_or("The resource collection has no parent directory.")?;
    let paths = if info.list_options.is_empty() {
        parse(&read(cx, &info.source, MAX_RESOURCE_FILE_BYTES)?).map_err(|error| {
            format!(
                "Cannot list resources in \"{}\". {error}.",
                info.source.display()
            )
        })?
    } else {
        let mut arguments = info.list_options.clone();
        let base = info
            .source
            .file_name()
            .ok_or("The resource collection has no file name.")?;
        arguments.push(from_native(Path::new(base)));
        let result = run_tool(cx, &info.executable, arguments, dir, info.common.verbose).map_err(
            |error| {
                format!(
                    "Cannot list resources in \"{}\".\n{error}",
                    info.source.display()
                )
            },
        )?;
        list_output(&result.stdout, &result.stderr).map_err(|error| {
            format!(
                "Cannot list resources in \"{}\".\n{error}",
                info.source.display()
            )
        })?
    };
    Ok(paths.iter().map(|path| resolve(dir, path)).collect())
}

fn list_output(stdout: &[u8], stderr: &[u8]) -> Result<Vec<BString>> {
    let mut paths = Vec::new();
    for line in resource_lines(stdout).filter(|line| !line.is_empty()) {
        add_path(&mut paths, line)?;
    }
    for line in resource_lines(stderr).filter(|line| line.starts_with(b"RCC: Error in")) {
        let prefix = b"Cannot find file '";
        let Some(index) = line.windows(prefix.len()).position(|part| part == prefix) else {
            return Err(format!(
                "The rcc list output is invalid: {}",
                BString::from(line)
            ));
        };
        let Some(path) = line
            .get(index + prefix.len()..)
            .and_then(|entry| entry.strip_suffix(b"'"))
        else {
            return Err(format!(
                "The rcc list output is invalid: {}",
                BString::from(line)
            ));
        };
        add_path(&mut paths, path)?;
    }
    Ok(paths)
}

fn resource_lines(output: &[u8]) -> impl Iterator<Item = &[u8]> {
    output
        .split(|&byte| byte == b'\n')
        .map(|line| line.split(|&byte| byte == b'\r').next().unwrap_or_default())
}

fn add_path(paths: &mut Vec<BString>, path: &[u8]) -> Result<()> {
    if paths.len() >= ITEM_LIMIT || path.contains(&0) {
        return Err("The rcc resource list has too many entries or an invalid path.".into());
    }
    paths.push(BString::from(path));
    Ok(())
}
