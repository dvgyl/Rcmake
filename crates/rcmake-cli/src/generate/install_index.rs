use std::path::Path;

use rcmake_base::{BString, truth};
use rcmake_gen_common::{GenError, install_script};
use rcmake_host::{Host, WriteMode, path};
use rcmake_json::{Value, write_styled};
use rcmake_model::{DirId, ProjectModel};
use rcmake_resolve::{InstallAction, InstallActionKind, InstallEntry, InstallManifest};

pub(super) fn write(
    host: &dyn Host,
    bin: &Path,
    model: &ProjectModel,
    manifest: &InstallManifest,
    options: install_script::InstallScriptOptions<'_>,
) -> Result<(), GenError> {
    let cmake_files = bin.join("CMakeFiles");
    let stamp = cmake_files.join("cmake.check_cache");
    host.create_dir_all(&cmake_files)
        .and_then(|()| host.write(&stamp, b"# This file is generated by cmake for dependency checking of the CMakeCache.txt file\n", WriteMode::Truncate))
        .map_err(|error| GenError::Write {
            path: path::from_native(&cmake_files),
            message: error.to_string().into(),
        })?;
    let parallel = model
        .global
        .props
        .get(b"INSTALL_PARALLEL")
        .is_some_and(|value| truth::is_on(value));
    let last = manifest
        .directories
        .values()
        .flatten()
        .filter_map(|entry| match entry {
            InstallEntry::Actions(range) => Some(range.end),
            InstallEntry::Child(_) => None,
        })
        .max()
        .unwrap_or(0);
    let mut scripts = Vec::new();
    for (id, dir) in model.dirs() {
        let Some(entries) = manifest.directories.get(&id) else {
            continue;
        };
        let mut local = InstallManifest::default();
        for entry in entries {
            match entry {
                InstallEntry::Actions(range) => {
                    let actions = manifest.actions.get(range.clone()).ok_or_else(|| {
                        GenError::Invalid("Invalid range of install actions.".into())
                    })?;
                    local.actions.extend_from_slice(actions);
                }
                InstallEntry::Child(child) => {
                    let code = install_script::include_child_script(&script_name(
                        &model.dir(*child).binary_dir,
                    ));
                    local.actions.push(InstallAction {
                        component: BString::default(),
                        all_components: true,
                        exclude_from_all: false,
                        destination: BString::default(),
                        configurations: Vec::new(),
                        kind: InstallActionKind::Code(code),
                        optional: false,
                        message: BString::default(),
                    });
                }
            }
        }
        if id == DirId::ROOT {
            local
                .actions
                .extend_from_slice(manifest.actions.get(last..).unwrap_or_default());
        }
        let mut options = options;
        options.top_level = false;
        let mut content = install_script::render_with_runtime_definitions(
            &local,
            &dir.binary_dir,
            &options,
            |name| model.definition(id, name),
        )?;
        content.extend_from_slice(
            br#"if(CMAKE_INSTALL_LOCAL_ONLY)
  string(REPLACE ";" "\n" CMAKE_INSTALL_MANIFEST_CONTENT "${CMAKE_INSTALL_MANIFEST_FILES}")
  if(NOT DEFINED _RCMAKE_INSTALL_LOCAL_MANIFEST)
    set(_RCMAKE_INSTALL_LOCAL_MANIFEST "${CMAKE_CURRENT_LIST_DIR}/install_local_manifest.txt")
  endif()
  file(WRITE "${_RCMAKE_INSTALL_LOCAL_MANIFEST}" "${CMAKE_INSTALL_MANIFEST_CONTENT}")
"#,
        );
        if id == DirId::ROOT {
            content.extend_from_slice(b"else()\n");
            install_script::render_manifest(&mut content, &dir.binary_dir);
        }
        content.extend_from_slice(b"endif()\n");
        let script = script_name(&dir.binary_dir);
        super::write(host, &path::to_native(&script), Ok(content))?;
        scripts.push(Value::string(script));
    }
    let mut fields = vec![
        (BString::from("InstallScripts"), Value::Array(scripts)),
        (BString::from("Parallel"), Value::Bool(parallel)),
    ];
    if model.generator == Some(rcmake_model::GeneratorKind::NinjaMultiConfig) {
        use rcmake_base::list::{Empty, split};
        let setting = |name: &[u8]| model.definition(DirId::ROOT, name);
        let available = setting(b"CMAKE_CONFIGURATION_TYPES")
            .map(|value| split(value, Empty::Drop))
            .unwrap_or_else(|| {
                ["Debug", "Release", "RelWithDebInfo"]
                    .map(BString::from)
                    .to_vec()
            });
        let configs = match setting(b"CMAKE_DEFAULT_CONFIGS") {
            Some(value) if value == b"all" => available,
            Some(value) => split(value, Empty::Drop),
            None => setting(b"CMAKE_DEFAULT_BUILD_TYPE")
                .cloned()
                .or_else(|| available.into_iter().next())
                .into_iter()
                .collect(),
        };
        fields.push((
            "Configs".into(),
            Value::Array(configs.into_iter().map(Value::string).collect()),
        ));
    }
    let value = Value::Object(fields.into_iter().collect());
    let file = cmake_files.join("InstallScripts.json");
    host.write(&file, &write_styled(&value, "  "), WriteMode::Truncate)
        .map_err(|error| GenError::Write {
            path: path::from_native(&file),
            message: error.to_string().into(),
        })
}

fn script_name(directory: &[u8]) -> BString {
    rcmake_base::path_lex::Lexical::new(directory).append(b"cmake_install.cmake")
}
