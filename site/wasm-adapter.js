function checkBasicSyntax(source) {
  let parens = 0;
  let inQuote = false;
  let escaped = false;
  let line = 1;
  const issues = [];

  for (let i = 0; i < source.length; i += 1) {
    const ch = source[i];
    if (ch === "\n") {
      line += 1;
      escaped = false;
      continue;
    }
    if (escaped) {
      escaped = false;
      continue;
    }
    if (ch === "\\" && inQuote) {
      escaped = true;
      continue;
    }
    if (ch === '"' ) {
      inQuote = !inQuote;
      continue;
    }
    if (!inQuote && ch === "#") {
      while (i < source.length && source[i] !== "\n") {
        i += 1;
      }
      line += 1;
      continue;
    }
    if (!inQuote) {
      if (ch === "(") {
        parens += 1;
      } else if (ch === ")") {
        parens -= 1;
        if (parens < 0) {
          issues.push({
            severity: "warning",
            category: "PREVIEW_SYNTAX",
            file: "CMakeLists.txt",
            line,
            column: 1,
            message: "Unmatched closing parenthesis detected in edited buffer."
          });
          parens = 0;
        }
      }
    }
  }

  if (inQuote) {
    issues.push({
      severity: "warning",
      category: "PREVIEW_SYNTAX",
      file: "CMakeLists.txt",
      line,
      column: 1,
      message: "Unterminated quoted argument detected in edited buffer."
    });
  }
  if (parens > 0) {
    issues.push({
      severity: "warning",
      category: "PREVIEW_SYNTAX",
      file: "CMakeLists.txt",
      line,
      column: 1,
      message: `${parens} unclosed command parenthesis detected in edited buffer.`
    });
  }
  return issues;
}

export class RcmakeWasmAdapter {
  constructor() {
    this.mode = "preview";
    this.module = null;
    this.bundleUrl = "./wasm/rcmake_wasm.js";
    this.loadReason = "WASM bundle not loaded yet.";
    this._lastContext = null;
  }

  /**
   * Attempt to dynamically import and initialize the compiled wasm-bindgen bundle.
   * Falls back cleanly to `"preview"` mode when `./wasm/rcmake_wasm.js` is absent.
   *
   * @param {string} [url="./wasm/rcmake_wasm.js"]
   * @returns {Promise<{mode: "wasm"|"preview", url: string, reason?: string}>}
   */
  async load(url = "./wasm/rcmake_wasm.js") {
    this.bundleUrl = url;
    try {
      const mod = await import(url);
      if (typeof mod.default === "function") {
        await mod.default();
      }
      if (typeof mod.configure_json !== "function") {
        throw new Error("Module loaded but missing configure_json export.");
      }
      this.module = mod;
      this.mode = "wasm";
      this.loadReason = "Loaded WebAssembly PureHost runtime.";
      return { mode: "wasm", url };
    } catch (err) {
      this.module = null;
      this.mode = "preview";
      this.loadReason = `Preview mode (WASM bundle pending at ${url}).`;
      return {
        mode: "preview",
        url,
        reason: err instanceof Error ? err.message : String(err)
      };
    }
  }

  /**
   * Run a configure pass over an in-memory virtual file tree.
   *
   * @param {Record<string, string>} files
   * @param {{ exampleId?: string, generator?: string, buildType?: string, preset?: string, defines?: Record<string, string> }} [options]
   */
  async configure(files, options = {}) {
    const generator = options.generator || "Ninja";
    const buildType = options.buildType || "Debug";
    const exampleId = options.exampleId || "hello-cpp20";

    if (this.mode === "wasm" && this.module) {
      const started = performance.now();
      const raw = this.module.configure_json(
        JSON.stringify({
          files,
          generator,
          buildType,
          preset: options.preset || null,
          defines: options.defines || {}
        })
      );
      const parsed = JSON.parse(raw);
      const durationMs = typeof parsed.durationMs === "number"
        ? parsed.durationMs
        : Number((performance.now() - started).toFixed(2));
      this._lastContext = { files, generator, buildType, exampleId, parsed };
      return {
        mode: "wasm",
        editedInPreview: false,
        durationMs,
        ...parsed
      };
    }

    const example = PLAYGROUND_EXAMPLES[exampleId] || PLAYGROUND_EXAMPLES["hello-cpp20"];
    const result = example.preview({ generator, buildType });
    const edited = Object.entries(example.files).some(
      ([path, baseline]) => (files[path] ?? "") !== baseline
    );

    const diagnostics = [...result.diagnostics];
    if (edited) {
      diagnostics.unshift({
        severity: "warning",
        category: "PREVIEW_MODE",
        file: "CMakeLists.txt",
        line: 1,
        column: 1,
        message: "Buffer modified in Preview mode: showing precomputed baseline output until ./wasm/rcmake_wasm.js is deployed."
      });
      diagnostics.push(...checkBasicSyntax(files["CMakeLists.txt"] || ""));
    }

    this._lastContext = { files, generator, buildType, exampleId, previewResult: result };

    return {
      mode: "preview",
      editedInPreview: edited,
      ok: result.ok,
      durationMs: result.durationMs,
      diagnostics,
      targets: result.targets,
      files: result.files,
      explainSymbols: Object.keys(result.explain)
    };
  }

  /**
   * Query `rcmake explain` provenance for a target or variable symbol.
   *
   * @param {string} symbol
   * @param {{ config?: string }} [options]
   */
  async explain(symbol, options = {}) {
    const trimmed = String(symbol || "").trim();
    if (!trimmed) {
      return {
        schema: "rcmake-explain-v1",
        kind: "not_found",
        name: "",
        details: { suggestions: [] }
      };
    }

    if (this.mode === "wasm" && this.module && typeof this.module.explain_json === "function" && this._lastContext) {
      const raw = this.module.explain_json(
        JSON.stringify({
          files: this._lastContext.files,
          symbol: trimmed,
          generator: this._lastContext.generator,
          buildType: this._lastContext.buildType,
          config: options.config || this._lastContext.buildType
        })
      );
      return JSON.parse(raw);
    }

    const previewResult = this._lastContext?.previewResult;
    if (previewResult && previewResult.explain[trimmed]) {
      return previewResult.explain[trimmed];
    }

    const available = previewResult ? Object.keys(previewResult.explain) : [];
    return {
      schema: "rcmake-explain-v1",
      kind: "not_found",
      name: trimmed,
      details: {
        suggestions: available.map((name) => ({
          name,
          kind: previewResult.explain[name].kind
        }))
      }
    };
  }
}
