"""Generate exact CMake 4.5.1 policy table (CMP0000..CMP0226) from the pinned oracle.

Reads `$RCMAKE_ORACLE_CMAKE --help-policy-list` and `--help-policy <CMP>` and writes
`crates/rcmake-diag/src/generated_policies.rs`.
"""

from __future__ import annotations

import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "rcmake-diag" / "src" / "generated_policies.rs"

VER_RE = re.compile(r"\.\.\s+versionadded::\s*(\d+)\.(\d+)(?:\.(\d+))?")
CMAKE_VER_RE = re.compile(r"introduced in CMake version\s+(\d+)\.(\d+)(?:\.(\d+))?", re.IGNORECASE)


# Empirically observed CMake 4.5.1 runtime policy summaries that differ from the
# first line of `--help-policy <CMP>`.
RUNTIME_SUMMARY_OVERRIDES: dict[int, str] = {
    140: "The ``return()`` command checks its arguments.",
    219: "Macro invocations preserve backslashes in arguments.",
}


def main() -> int:
    cmake = os.environ.get("RCMAKE_ORACLE_CMAKE")
    if not cmake or not pathlib.Path(cmake).is_file():
        print("ERROR: RCMAKE_ORACLE_CMAKE must point to the pinned cmake 4.5.1 binary", file=sys.stderr)
        return 1

    plist = subprocess.check_output([cmake, "--help-policy-list"], text=True).splitlines()
    policies = [line.strip() for line in plist if re.fullmatch(r"CMP\d{4}", line.strip())]
    if not policies:
        print("ERROR: no policies returned by --help-policy-list", file=sys.stderr)
        return 1

    rows: list[tuple[int, int, int, int, bool, str]] = []
    for pol in policies:
        num = int(pol[3:])
        doc = subprocess.check_output([cmake, "--help-policy", pol], text=True)
        lines = doc.splitlines()

        # First non-empty prose paragraph after title & .. versionadded::
        major, minor, patch = 3, 0, 0
        m = VER_RE.search(doc) or CMAKE_VER_RE.search(doc)
        if m:
            major = int(m.group(1))
            minor = int(m.group(2))
            patch = int(m.group(3) or 0)
        elif num <= 11:
            major, minor, patch = 2, 6, 0
        elif num <= 17:
            major, minor, patch = 2, 8, 0

        summary = ""
        for idx, line in enumerate(lines):
            if idx < 2:
                continue
            s = line.strip()
            if not s or s.startswith("..") or set(s) <= {"-", "=", "~"}:
                continue
            summary = s
            break
        summary = RUNTIME_SUMMARY_OVERRIDES.get(num, summary)
        summary = summary.replace("\\", "\\\\").replace('"', '\\"')
        removed_old = num <= 65
        rows.append((num, major, minor, patch, removed_old, summary))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        f.write("// @generated by tools/gen/gen_policies.py from pinned CMake 4.5.1 oracle.\n")
        f.write("// Do not hand-edit; re-run `python3 tools/gen/gen_policies.py`.\n\n")
        f.write("use crate::policy::{PolicyId, PolicyInfo};\n\n")
        f.write(f"/// Highest policy numeric ID known to CMake 4.5.1 (`CMP{rows[-1][0]:04}`).\n")
        f.write(f"pub const MAX_POLICY_ID: u16 = {rows[-1][0]};\n\n")
        f.write("/// Highest policy numeric ID whose `OLD` behavior was removed in CMake 4.0+.\n")
        f.write("pub const MAX_REMOVED_OLD_POLICY_ID: u16 = 65;\n\n")
        f.write("/// Complete CMake 4.5.1 policy registry (`CMP0000` through `CMP0226`).\n")
        f.write("pub static POLICIES: &[PolicyInfo] = &[\n")
        for num, maj, min_, pat, rem, summary in rows:
            f.write(
                f'    PolicyInfo {{ id: PolicyId::new({num}), introduced: ({maj}, {min_}, {pat}), '
                f'removed_old: {str(rem).lower()}, summary: "{summary}" }},\n'
            )
        f.write("];\n")

    print(f"Generated {len(rows)} policies (CMP{rows[0][0]:04}..CMP{rows[-1][0]:04}) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
